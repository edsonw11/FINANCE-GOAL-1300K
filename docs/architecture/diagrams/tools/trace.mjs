/**
 * trace.mjs
 * Responsibility: proves that every box of a diagram points at something real (the file exists, the named symbol is in it) and builds the traceability matrix from those proofs.
 * Nothing here is typed by hand: a rename in the code makes the build fail until the diagram is fixed.
 */
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';

export function traceRows(diagrams, root) {
  const rows = [], errors = [];
  let n = 0;
  for (const d of diagrams) for (const [pi, page] of d.pages.entries()) {
    const items = page.lanes ? page.lanes.flatMap((l) => l.nodes) : page.participants;
    const seen = new Set();
    for (const it of items) {
      if (seen.has(it.id)) errors.push(`${d.id}: duplicate id ${it.id}`);
      seen.add(it.id);
      let evidence = 'external system or concept (see the integration note)';
      if (it.src) {
        const file = path.join(root, it.src);
        if (!existsSync(file)) { errors.push(`${d.id}/${it.id}: file not found ${it.src}`); continue; }
        evidence = it.src;
        if (it.sym) {
          const lines = readFileSync(file, 'utf8').split('\n'), at = lines.findIndex((l) => l.includes(it.sym));
          if (at < 0) { errors.push(`${d.id}/${it.id}: symbol "${it.sym}" not found in ${it.src}`); continue; }
          evidence = `${it.src}:${at + 1}`;
        }
      } else if (it.status === 'IMPLEMENTED') errors.push(`${d.id}/${it.id}: an IMPLEMENTED item needs a source file`);
      rows.push({ id: `TM-${String(++n).padStart(3, '0')}`, component: it.title, diagram: `${d.id}${d.pages.length > 1 ? ' / ' + (page.name || pi + 1) : ''}`, file: it.src || '-', symbol: it.sym || '-', status: it.status || 'IMPLEMENTED', evidence });
    }
    for (const e of page.edges || []) if (!seen.has(e.from) || !seen.has(e.to)) errors.push(`${d.id}: edge ${e.from} -> ${e.to} has an unknown end`);
    for (const m of page.messages || []) if (!seen.has(m.from) || !seen.has(m.to)) errors.push(`${d.id}: message ${m.from} -> ${m.to} has an unknown end`);
  }
  return { rows, errors };
}
export const matrixMarkdown = (rows) => `# Traceability matrix

Generated by \`docs/architecture/diagrams/tools/build.mjs\` from the diagram specifications: each row was checked against the code when it was generated (the file exists, the symbol is in the file, the evidence is the line where it was found). Do not edit by hand: change the specification and run \`node docs/architecture/diagrams/tools/build.mjs\`.

| ID | Component | Diagram | Source file | Class / function | Status | Evidence |
|---|---|---|---|---|---|---|
${rows.map((r) => `| ${r.id} | ${r.component} | ${r.diagram} | ${r.file === '-' ? '-' : '\`' + r.file + '\`'} | ${r.symbol === '-' ? '-' : '\`' + r.symbol + '\`'} | ${r.status} | ${r.evidence.startsWith('external') ? r.evidence : '\`' + r.evidence + '\`'} |`).join('\n')}
`;
