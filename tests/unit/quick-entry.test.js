/** Quick entry by sentence: fixed rules, nothing invented, missing pieces are reported. */
const {createContext,suite}=require('./harness');
module.exports=()=>{const {run}=createContext(),{eq,ok,res}=suite('quick-entry');
  const J=JSON.stringify;
  run(`S=seed();S.tx=[];initCats();`);
  const q=t=>run(`parseQuickEntry(${J(t)},'2026-11-10')`);
  let r=q('Gastei 85,90 no mercado hoje');
  eq('expense: value, category from the catalog, today',[r.type,r.value,r.cat,r.date,r.missing],['despesa',85.9,'Mercado','2026-11-10',[]]);
  eq('description is what is left',r.desc,'Mercado');
  r=q('Recebi 5.000 de salário dia 5');
  eq('income on day 5 of this month',[r.type,r.value,r.cat,r.date,r.missing],['receita',5000,'Salário','2026-11-05',[]]);
  r=q('Paguei 230 de internet no cartão Nubank');
  eq('card expense, card name is only a note',[r.type,r.value,r.cat,r.fonte],['despesa',230,'Internet','cartao']);
  ok('does not pretend to know the card',r.notes.some(n=>/Nubank/.test(n)&&/cartão cadastrado/.test(n)));
  r=q('Aporte de 1.000 no Tesouro Selic em 10/11');
  eq('ambiguous account is not guessed',[r.type,r.value,r.date,r.acc,r.missing],['aporte',1000,'2026-11-10','',['acc']]);
  ok('lists the candidates',/Tesouro Selic 2028 ou Tesouro Selic 2031/.test(r.notes.join(' ')));
  r=q('Aporte de 1.000 no Tesouro Selic 2031 em 10/11');
  eq('unique account is found',[r.acc,r.missing],['s31',[]]);
  r=q('gastei 20 ontem na padaria');
  eq('yesterday',r.date,'2026-11-09');
  eq('unknown category is missing, not invented',[r.cat,r.missing],['',['cat']]);
  r=q('gastei 20 anteontem');
  eq('day before yesterday',r.date,'2026-11-08');
  r=q('gastei 45 em 03/10/2026 na farmácia');
  eq('full date',r.date,'2026-10-03');
  r=q('gastei 45 dia 31 no mercado');
  eq('day that does not exist this month is reported',[r.date,r.missing.includes('date')],['2026-11-10',true]);
  r=q('gastei no mercado');
  eq('no value is reported',[r.value,r.missing.includes('value')],[0,true]);
  r=q('mercado 50');
  eq('no verb: assumes expense but says so',[r.type,r.missing.includes('type')],['despesa',true]);
  r=q('gastei R$ 1.234,56 no mercado');
  eq('R$ and separators',r.value,1234.56);
  r=q('paguei 2000 de aluguel dia 5');
  eq('plain integer value, day is not the value',[r.value,r.date],[2000,'2026-11-05']);
  r=q('Gastei 85,90 no mercado.');
  eq('trailing punctuation is ignored',[r.value,r.cat],[85.9,'Mercado']);
  r=q('gastei 30 no pix padaria');
  eq('pix means cash/account',r.fonte,'caixa');
  // history: same description seen before -> category from history (exact only)
  run(`S.tx.push({id:S.nid++,type:'despesa',date:'2026-10-01',value:30,desc:'Feira do bairro',cat:'Mercado',fonte:'caixa'})`);
  r=q('gastei 40 na feira do bairro');
  eq('exact history gives the category',[r.cat,r.missing],['Mercado',[]]);
  ok('and says where it came from',r.notes.some(n=>/histórico/.test(n)));
  eq('connecting words inside the description are kept',q('gastei 40 na feira do bairro').desc,'Feira do bairro');
  eq('and the ones at its edges are dropped',q('gastei 40 de gasolina no').desc,'Gasolina');
  eq('summary is readable',q('Gastei 85,90 no mercado hoje').summary,'despesa · R$ 85,90 · Mercado · hoje');
  return res;};
